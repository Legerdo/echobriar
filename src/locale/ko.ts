/** 받침 여부에 따른 조사 선택: josa('빈 갑주', '이', '가') → '빈 갑주가' */
export function josa(word: string, withBatchim: string, without: string): string {
  const ch = word.trim().slice(-1);
  const code = ch.charCodeAt(0) - 0xac00;
  if (code < 0 || code > 11171) return `${word}${withBatchim}(${without})`;
  const jong = code % 28;
  // '(으)로'는 ㄹ받침도 '로'
  if (withBatchim === '으로' && jong === 8) return `${word}${without}`;
  return `${word}${jong ? withBatchim : without}`;
}
/** 조사만 반환 (따옴표로 감싼 이름 뒤에 붙일 때) */
export function pt(word: string, withBatchim: string, without: string): string {
  return josa(word, withBatchim, without).slice(word.length);
}

